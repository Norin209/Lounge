const fs = require('node:fs');
const assert = require('node:assert/strict');
const Module = require('node:module');
const root = require('node:path').resolve(__dirname, '..');
const ts = require(root + '/node_modules/typescript');
require.extensions['.ts'] = (module, filename) => {
  module.paths.push(...Module._nodeModulePaths(root));
  module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2021 } }).outputText, filename);
};
const { financeSummary } = require(root + '/app/admin/earnings/finance-summary.ts');
const revenue = { key: '2026-09', totalCents: 1340998 };
const expenses = { key: '2026-09', hasExpenseSheet: true, expenses: [{ category: 'Salon', total: 4985.41 }, { category: 'Salaries', total: 3286.58 }] };
const salary = { key: '2026-09', finalTotal: 3286.58 };
let result = financeSummary(revenue, expenses, salary);
assert.equal(result.revenueCents, 1340998);
assert.equal(result.expenseCents, 827199);
assert.equal(result.payrollCents, 328658);
assert.equal(result.afterExpenseCents, 513799);
assert.deepEqual(result.missing, []);
console.log('PASS matched September: salaries counted once, balance 5137.99');
result = financeSummary(revenue, { ...expenses, hasExpenseSheet: false }, salary);
assert.equal(result.afterExpenseCents, 513799);
assert.ok(result.missing.includes('Daily expenses missing'));
console.log('PASS incomplete expense coverage keeps a provisional balance and its note');
result = financeSummary(undefined, expenses, salary);
assert.equal(result.revenueCents, null); assert.equal(result.afterExpenseCents, null);
result = financeSummary(revenue, undefined, undefined);
assert.equal(result.expenseCents, null); assert.equal(result.payrollCents, null); assert.equal(result.afterExpenseCents, revenue.totalCents);
result = financeSummary(revenue, expenses, undefined);
assert.equal(result.afterExpenseCents, 513799); assert.ok(result.missing.includes('Payroll missing'));
console.log('PASS missing sales stay unavailable; missing expenses/payroll keep provisional balances');
result = financeSummary({ ...revenue, totalCents: 0 }, { ...expenses, expenses: [] }, { ...salary, finalTotal: 0 });
assert.equal(result.afterExpenseCents, 0); assert.deepEqual(result.missing, []);
console.log('PASS real zero values remain valid');
result = financeSummary({ ...revenue, totalCents: 10000 }, expenses, salary);
assert.equal(result.afterExpenseCents, -817199);
console.log('PASS loss remains negative');
